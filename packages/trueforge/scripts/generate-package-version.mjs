/**
 * Inlines package.json `version` into a generated TS module so nothing reads
 * package.json at runtime (Workers bundles have no package files on disk).
 *
 * Runs via `build:gen` before build/typecheck/test/dev. The generated output
 * (src/packageVersion.gen.ts) is gitignored.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'));
if (typeof version !== 'string' || version.length === 0) {
  throw new Error('package.json version must be a non-empty string');
}

const out = `// AUTO-GENERATED by scripts/generate-package-version.mjs — do not edit.
/** Package version for logs, the OpenAPI document, and the CLI. */
export const PACKAGE_VERSION = ${JSON.stringify(version)};
`;
writeFileSync(join(root, 'src/packageVersion.gen.ts'), out);
