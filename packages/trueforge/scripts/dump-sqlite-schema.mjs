// Regenerates migrations/d1/0001_init.sql from the Kysely SQLite migrations (D1 does not run them).
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { sql } from 'kysely';

import { migrateSqliteToLatest } from '../src/db/migrateSqlite.ts';
import { createSqliteDb } from '../src/db/sqlite/client.ts';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(packageRoot, 'migrations', 'd1', '0001_init.sql');
// Tables first so indexes and triggers always follow the table they reference.
const TYPE_ORDER = ['table', 'index', 'view', 'trigger'];

const tempDir = await mkdtemp(path.join(os.tmpdir(), 'trueforge-d1-schema-'));
const db = createSqliteDb(path.join(tempDir, 'schema.sqlite'));
try {
  await migrateSqliteToLatest(db);
  const { rows } = await sql`
    SELECT type, name, sql FROM sqlite_master
    WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'kysely_migration%'
  `.execute(db);
  const statements = rows
    .toSorted(
      (a, b) =>
        TYPE_ORDER.indexOf(a.type) - TYPE_ORDER.indexOf(b.type) || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0),
    )
    .map(row => `${row.sql};`);
  const header = '-- Generated by `pnpm d1:schema:dump` from the Kysely SQLite migrations. Do not edit.\n\n';
  await mkdir(path.dirname(outFile), { recursive: true });
  await writeFile(outFile, `${header}${statements.join('\n\n')}\n`);
  console.log(`Wrote ${String(statements.length)} statements to ${path.relative(process.cwd(), outFile)}`);
} finally {
  await db.destroy();
  await rm(tempDir, { recursive: true, force: true });
}
